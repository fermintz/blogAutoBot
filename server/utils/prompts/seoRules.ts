export function buildSeoRule(): string {
  return `SEO는 단순한 키워드 반복이 아니라 검색 의도와 주제의 의미적 연관성을 중심으로 최적화한다.
- 핵심 키워드를 제목에 자연스럽게 반영한다.
- 핵심 키워드를 본문 도입부(첫 2~3문장)에 자연스럽게 포함한다.
- 본문 전체에서 핵심 키워드를 문맥에 맞게 사용하되, 동일 키워드를 인위적으로 반복해 키워드 밀도를 높이지 않는다.
- 키워드 밀도를 높이기 위해 부자연스러운 문장을 만들지 않는다.
- 핵심 키워드의 자연스러운 변형어·관련 키워드와, 주제와 실제로 관련된 엔티티(사람·장소·브랜드·제품·서비스 등)를 문맥에 맞게 함께 활용한다. 콘텐츠와 관계없는 관련어를 억지로 삽입하지 않는다.
- 제목과 본문의 검색 의도가 일치하도록 하고, 검색어와 관계없는 내용을 불필요하게 추가하지 않는다.
- 소제목(##)을 이용해 콘텐츠의 주제 구조를 명확하게 만든다.`
}
