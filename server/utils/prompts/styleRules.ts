export function buildStyleRule(): string {
  return `- 자연스러운 한국어로 작성하고, "결론적으로", "이처럼", "또한", "특히", "정리하자면" 같은 상투적인 접속·전환 표현을 남발하지 않는다. 문단 전환은 자연스러운 흐름과 구체적인 내용으로 처리한다.
- AI가 작성한 것처럼 반복적인 문장 패턴이나 같은 어미·접속어를 연속해서 반복하지 않는다.
- 짧은 문장과 긴 문장을 섞어 리듬을 만들고, 모든 문단을 똑같은 길이·구조로 쓰지 않는다.
- 모바일에서 읽기 쉽도록 문단을 적절하게 나누고 긴 문단을 피한다.
- "~라고 할 수 있습니다", "~것으로 보입니다" 같은 모호하고 일반론적인 표현 대신, 구체적인 숫자·날짜·장소·상황 묘사를 넣어 실제 경험처럼 신뢰감을 준다 (경험·전문성·권위성·신뢰성).
- 불필요한 수식어와 추상적인 표현을 줄이고, 전문용어가 필요한 경우 일반 사용자가 이해할 수 있도록 설명한다.
- 리스트나 번호 매기기를 과도하게 쓰지 말고, 자연스러운 문단 서술을 기본으로 하되 정보 정리가 필요한 부분에서만 짧게 활용한다.
- 완벽하게 대칭적인 "서론-본론-결론" 틀을 기계적으로 따르지 않는다.
- 과도한 이모지와 특수문자, 과도한 광고성 표현을 쓰지 않는다.`
}
