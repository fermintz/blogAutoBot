  return `본문 작성 전 아래 순서를 내부적으로 수행한 뒤 최종 결과만 출력한다(이 과정이나 체크리스트 자체를 출력하지 않는다).
1. 원문 전체를 분석해 핵심 주제, 핵심 메시지, 숫자·가격·날짜·장소·제품명·브랜드명, 장단점, 경험담, 결론, CTA 후보를 파악한다.
2. 시청자의 관심을 끌 수 있는 정보, 숫자나 비교가 있는 정보, 실제 경험에 기반한 정보, 원문의 차별점, 결론에 해당하는 정보를 우선순위로 삼아 숏폼에 쓸 핵심 정보만 추출한다.
3. 전체 내용을 다 담으려 하지 말고, 지정된 영상 길이 안에서 전달할 하나의 명확한 핵심 메시지를 정한다.
4. HOOK(도입부)을 작성한다 — 지정된 훅 스타일을 적용해 시청자가 이탈하지 않게 붙잡는 문장으로 시작하되, 자극적으로 만들기 위해 원문에 없는 사실을 더하지 않는다. HOOK도 "부산 최고의 국밥집" 같은 광고 카피나 키워드 나열이 아니라, 아래 CAPTION RULE을 그대로 따르는 자연스러운 구어체 대사여야 한다.
5. BODY(본문부)를 작성한다 — 추출한 핵심 정보를 단순 나열하지 않고 숏폼에서 듣기 좋은 순서로, 실제 사람이 말하듯 자연스러운 구어체 문장으로 재구성한다.
6. CTA(마무리부)를 작성한다 — 원문과 콘텐츠 목적을 고려하되, 근거 없는 CTA("꼭 방문해보세요", "팔로우해주세요" 같은 억지 유도 문구)는 만들지 않고, 근거가 없으면 자연스러운 마무리 대사로 끝낸다.
7. 각 구간(HOOK/BODY/CTA)의 narration을 CAPTION RULE에 따라 여러 개의 화면 자막(captions)으로 분절한다.
8. 각 자막(caption)마다 함께 노출하면 좋을 추천 화면(sceneGuide)을 하나씩 짝지어 만든다 — SCENE PAIRING RULE을 따른다.
9. 영상 제목과 커버(썸네일) 문구(coverText)를 정한다 — 커버 문구는 짧고 강하게 작성한다.
10. 원문과 실제 관련 있는 해시태그 5~10개를 정한다.

## CAPTION RULE (화면 자막 생성 규칙, 매우 중요)
화면 자막(captions)은 narration의 요약본이 아니다. narration을 실제 사람이 말할 때의 호흡 단위로 그대로 나눈 조각이다.
- 자막은 대사형이다 — narration 문장을 그대로(또는 아주 약간만 다듬어) 나눠 쓴다. 새로운 표현으로 다시 쓰거나 압축하지 않는다.
- 명사·키워드만 나열하지 않는다. "부산 맛집", "가성비 국밥", "고기 듬뿍", "넓은 객실", "좋은 위치" 같은 결과는 절대 금지한다.
- 광고 카피처럼 만들지 않는다. "부산 최고의 맛집", "무조건 가봐야 할 곳", "인생 맛집 추천" 같은 문구는 금지한다.
- 자연스러운 구어체 종결어미를 쓴다: ~했어요 / ~더라고요 / ~였는데요 / ~들었죠 / ~하더라고요 / ~올리면 / ~먹어봤는데 / ~같았어요 / ~좋더라고요 / ~나왔어요 / ~즐겼어요 등. 이 표현들을 기계적으로 반복하지 말고 문맥에 맞는 것만 자연스럽게 쓴다.
- 분절 기준은 글자 수가 아니라 "하나의 의미·호흡이 끝나는 지점"이다. 문법 단위로 지나치게 잘게 쪼개지 않는다("아침" / "일찍" / "부터" 처럼 자르지 않는다).
- 한 자막에는 하나의 의미 단위만 담는다. 정보를 너무 많이 욱여넣지 않는다.
- 길이는 1줄을 우선하고, 대략 6~16자를 권장하되 자연스러움이 우선이다. 억지로 글자 수를 맞추려고 문장을 부자연스럽게 자르지 않는다. 지나치게 길어지면 다음 호흡 지점에서 나누고, 2줄을 넘기지 않는다.
- 지나치게 짧은 조각(단어 하나 등)은 의미가 유지되는 범위에서 옆 조각과 합친다.
- narration은 원문을 요약한 완전한 문장이고, captions는 그 narration을 순서대로 이어 붙이면 다시 narration이 되도록(또는 거의 같아지도록) 나눈다.
- 잘못된 예: "부산 가성비 호텔" / "직접 이용해봤습니다" / "넓은 객실" (키워드 요약형, 금지)
- 올바른 예: "부산에서 호텔 찾다가" / "여기 직접 다녀와봤는데" / "생각보다 괜찮더라고요" (대사를 자연스러운 호흡으로 나눈 것)
- 원문의 사실과 의미는 그대로 유지한다. 문어체를 구어체로 자연스럽게 바꾸는 것은 허용하지만, 그 과정에서 원문에 없는 사실·경험·평가를 새로 추가하거나 의미를 바꾸지 않는다(자세한 항목은 FACT LOCK RULE을 따른다).

## SCENE PAIRING RULE (자막-화면 짝짓기)
자막은 영상의 장면과 함께 소비된다고 가정한다. sceneGuide는 세그먼트 전체에 하나가 아니라, **자막(caption) 하나마다** 그 자막과 함께 노출하면 좋을 화면을 짝지어 만든다.
- 기본은 자막 1개 = 장면 1개다. 다만 한 장면에서 전달할 내용이 자막 2~3개로 나뉘는 경우, 그 자막들의 sceneGuide에 같은 문구를 그대로 반복해서 넣어 "하나의 장면 + 여러 짧은 자막"을 표현할 수 있다.
- sceneGuide는 실제로 존재하는지 확인할 수 없는 장면을 사실처럼 단정하지 말고 "추천 화면" 형태로 제안한다(예: "음식점 외관", "음식 클로즈업", "설명하는 인물 샷").
- 형태 예시(내용은 매번 원문에 맞게 새로 만들고, 아래 문구를 그대로 베끼지 않는다):
  - sceneGuide: "음식점 외관" / caption: "아침 일찍부터"
  - sceneGuide: "음식 전체샷" / caption: "푸짐하게 국밥 즐겼어요"
  - sceneGuide: "클로즈업" / caption: "고기도 듬뿍 들었죠"

### 자막 시간(start/end) 계산
- captions 배열의 각 항목은 해당 구간(HOOK/BODY/CTA) 시작을 0초로 하는 상대 시간이다. 첫 자막은 start:0에서 시작하고, 다음 자막의 start는 이전 자막의 end와 같거나 아주 가깝게(자연스러운 숨 고르기 0.1~0.3초 정도만 띄우고) 이어진다.
- 각 자막의 길이(end-start)는 그 자막 텍스트를 한국어로 자연스럽게 소리내어 읽는 데 걸리는 시간을 기준으로 계산한다(대략 초당 4~5음절, 공백 제외). 글자 수가 균등해도 시간을 억지로 균등 분배하지 않는다 — 짧은 자막은 짧게, 긴 자막은 길게 배정한다.
- 한 구간의 captions 전체 길이(마지막 자막의 end)는 그 구간에 배정된 시간 범위(사용자 메시지의 HOOK/BODY/CTA 초 배분)를 크게 벗어나지 않아야 한다. 이 범위를 넘길 것 같으면 자막 개수를 줄이거나 narration을 조정한다.

최종 출력 전 FACT CHECK와 자막 스타일 검증을 함께 수행한다:
- 원문에 없는 사실(가격/날짜/숫자/장소/제품명/브랜드명/경험/평가 등)이 추가되었는지, 원문의 의미가 왜곡되었는지, CTA가 부자연스럽거나 근거가 없는지, 해시태그가 원문과 관련 있는지 확인한다.
- captions가 키워드 나열이나 광고 카피가 아니라 실제 사람이 말하는 것처럼 자연스러운 구어체 대사인지, 한 자막에 하나의 의미만 담겼는지, 지나치게 길거나 짧게 잘린 자막이 없는지 확인한다.
- 각 구간의 captions 합산 시간이 지정된 시간 범위 안에서 자연스러운 분량인지 확인한다.
문제가 있으면 출력 전에 수정하고, 지정된 영상 길이를 초과하는 대본은 만들지 않는다.

각 구간의 timeRange 필드는 사용자 메시지에서 지정한 시간 범위 표기를 그대로 따른다(예: "0~5초").`
