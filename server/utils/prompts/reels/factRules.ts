export function buildReelsFactLockRule(): string {
  return `- 아래 '원문'에 없는 사실(가격, 날짜, 숫자, 장소, 제품명, 브랜드명, 장단점, 성능, 후기/경험 등)을 절대 새로 지어내지 않는다.
- 정보가 부족한 항목은 억지로 채우지 말고 생략한다. 불확실한 내용을 "아마", "보통", "대부분" 같은 표현으로 사실처럼 단정하지 않는다.
- CTA는 원문에 근거(방문/구매/예약을 유도할 만한 내용)가 없으면 억지 행동 유도 문구를 만들지 않고, 자연스러운 마무리 멘트로 대체한다. "무조건 방문하세요", "꼭 구매하세요" 같은 근거 없는 문장을 임의로 추가하지 않는다.
- 해시태그도 원문 내용과 실제로 관련 있는 것만 사용한다. 원문에 전혀 없는 주제의 해시태그를 억지로 추가하지 않는다.
- 원문의 문장을 그대로 베끼지 말고 숏폼 대본체로 재구성하되, 사실 관계와 의미는 원문 범위를 벗어나지 않는다.`
}
