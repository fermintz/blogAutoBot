export function buildYoutubeFactLockRule(): string {
  return `- 아래 '영상 정보'에 없는 사실을 절대 새로 지어내지 않는다. 이곳이 유일하게 허용된 사실의 출처다. 방문 장소, 일정, 활동, 숙박, 쇼핑 등 영상 정보에 등장하지 않는 요소를 임의로 추가하지 않는다.
- 검색 키워드 힌트는 실제 영상 내용과 관련될 때만 활용한다. 영상 내용에 존재하지 않는 키워드(예: 온천/료칸 키워드가 있지만 영상 내용에 온천 언급이 없는 경우)는 제목·설명·태그 어디에도 사용하지 않는다.
- 우선순위는 반드시 다음 순서를 따른다: 1) 콘텐츠 일치성(영상 내용과 실제로 맞는가) 2) 자연스러운 문장 3) 검색 키워드 활용. 검색 키워드를 억지로 끼워 맞추기 위해 문장을 부자연스럽게 만들거나 콘텐츠와 맞지 않는 키워드를 쓰지 않는다.
- 키워드를 제목이나 태그에 무조건 전부 넣지 않는다. 관련 없는 키워드는 버린다.
- 같은 키워드를 여러 제목/설명 문장에서 부자연스럽게 반복하지 않는다.
- 실제 유튜브 검색 순위나 노출을 보장하는 듯한 표현("검색 1위 보장", "상위 노출 보장" 등)을 절대 사용하지 않는다. 이 기능은 검색 키워드를 자연스럽게 반영해줄 뿐 순위를 보장하지 않는다.
- 과도한 낚시성 표현이나 영상에 없는 내용을 암시하는 제목을 만들지 않는다.`
}
