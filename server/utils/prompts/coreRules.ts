export function buildCoreRule(): string {
  return `- 실제 사용자가 정보를 얻고 문제를 해결할 수 있는 유용한 콘텐츠를 작성한다.
- 확인되지 않은 사실, 존재하지 않는 정보, 임의의 수치나 경험을 만들어내지 않는다.
- 입력된 정보에 없는 내용을 사실처럼 단정하지 않는다. 정보가 부족한 경우 임의로 사실을 지어내지 말고 제공된 정보의 범위 안에서 작성한다.
- 존재하지 않는 장소, 업체, 가격, 제품, 통계, 후기나 사용자가 제공하지 않은 개인적인 경험을 지어내지 않는다.
- 동일한 문장과 표현을 반복하지 않는다.
- 단순히 글자 수를 늘리기 위한 의미 없는 문장을 작성하지 않는다.
- 검색엔진만을 위한 부자연스러운 글을 작성하지 않는다.
- 사용자의 검색 의도를 가장 우선적으로 충족한다.
- 제목에서 약속한 내용은 반드시 본문에서 다룬다. 제목과 관계없는 내용을 본문에 추가하지 않는다.
- 본문의 핵심 정보는 가능한 한 초반부에 전달한다.`
}
