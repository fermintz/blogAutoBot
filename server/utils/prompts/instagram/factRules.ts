export function buildInstagramFactLockRule(): string {
  return `- 사실의 출처는 딱 두 곳뿐이다: 아래 'STORE_INFO'(네이버 지역 검색 결과 또는 사용자가 직접 수정한 매장 정보)와 '방문 정보'(사용자가 직접 입력한 지역/방문 메뉴/방문 후기/강조사항/메모). 이 두 곳에 없는 사실을 절대 새로 지어내지 않는다.
- 우선순위: 사용자가 직접 입력·수정한 값이 항상 1순위다. STORE_INFO는 그 값이 사용자 수정을 거치지 않았을 때만 참고하는 2순위 출처다. 이 두 곳 어디에도 없는 내용을 AI가 일반적인 글쓰기 능력으로 지어내는 것(3순위)은 허용되지 않는다 — 정보가 없으면 그 항목은 그냥 다루지 않는다.
- 특히 메뉴, 재료, 맛, 가격, 영업시간, 휴무일, 주차 가능 여부, 웨이팅, 이벤트, 시설, 서비스, 직원 친절도, 분위기, 매장 특징은 STORE_INFO나 방문 정보에 값이 있을 때만 언급한다. 방문 메뉴(visitedMenus)에 없는 메뉴를 먹은 것처럼 쓰지 않는다.
- 실제로 방문하거나 이용해본 것처럼 1인칭 경험을 지어내지 않는다("직접 가보니", "먹어보니", "이용해보니" 등의 표현을 방문 후기에 없는 경험에 붙이지 않는다). 방문 후기(reviewNotes)에 담긴 경험만 1인칭 후기로 표현한다.
- STORE_INFO와 방문 정보 어디에도 없는 항목은 본문에서 언급 자체를 생략한다. 정보가 없다고 해서 "주차 정보는 확인이 필요해요"처럼 없다는 사실을 언급하지도 않는다 — 그냥 다루지 않는다.
- 감성적인 표현은 STORE_INFO·방문 정보에 있는 사실에 대한 느낌으로만 쓴다. 예를 들어 한옥이라는 카테고리/설명이 있다면 그 사실에 대한 감성 표현은 가능하지만, 그런 사실이 없는데 임의로 만들어 붙이지 않는다.
- 매장명, 주소, 영업시간, 주차 정보, 전화번호, 인스타그램 계정 등 STORE_INFO의 값 자체를 임의로 바꾸거나 다르게 표현하지 않는다.
- 이 규칙은 응답의 body와 hashtags 모두에 동일하게 적용된다. 해시태그도 STORE_INFO·방문 정보의 카테고리·지역·메뉴·특징과 실제로 관련 있는 것만 만든다.`
}
