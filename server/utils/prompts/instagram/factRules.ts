import type { InstagramTopic } from '../../../../shared/types'
import { INSTAGRAM_CATEGORY_CONFIG } from './categoryConfig'

/** 객관적 사실 금지 목록은 카테고리와 무관하게 공통이다(가격/시설/운영시간/위치/서비스 정책 등은 어떤 카테고리든 똑같이 보수적으로 다뤄야 한다). 카테고리마다 달라지는 건 "새로 추가하면 안 되는 대상"을 부르는 명사(entityWord)뿐이라 categoryConfig에서만 가져온다. */
export function buildInstagramFactLockRule(topic: InstagramTopic): string {
  const entityWord = INSTAGRAM_CATEGORY_CONFIG[topic].entityWord

  return `사실은 성격이 다른 두 종류로 나눠서 다룬다. 아래 A(객관적 정보)와 B(주관적 경험)를 혼동하지 않는다.

### A. 객관적 정보 — 절대 지어내지 않는다
- 출처는 딱 두 곳뿐이다: 'STORE_INFO'(네이버 지역 검색 결과 또는 사용자가 직접 수정한 정보)와 '방문 정보'(사용자가 직접 입력한 지역/방문 경험). 이 두 곳에 없는 객관적 사실을 절대 새로 지어내지 않는다.
- 특히 가격, 할인, 이벤트, 영업시간, 휴무일, 주소, 전화번호, 주차 가능 여부·요금·대수, 입장료, 예약 가능 여부, 객실 수·크기, 침대 종류, 특정 시설의 위치, 수영장 유무, 조식 제공 여부, 무료 제공 서비스, 직원의 행동, 실제 대기시간, 실제 방문객 수, 특정 메뉴·상품의 가격, 특정 시설의 운영시간, 실제 이용 가능 여부, 실제 거리, 실제 소요시간은 STORE_INFO나 방문 정보에 값이 있을 때만 언급한다. 정보가 없으면 그 항목은 언급 자체를 생략한다 — "주차 정보는 확인이 필요해요"처럼 없다는 사실 자체도 언급하지 않는다.
- 방문 정보에 언급되지 않은 ${entityWord}를 새로 추가하지 않고, 언급된 이름을 임의로 다른 것으로 바꾸지 않는다.
- 이름, 주소, 영업시간, 주차 정보 등 STORE_INFO의 값 자체를 임의로 바꾸거나 다르게 표현하지 않는다.

### B. 주관적 경험 — CATEGORY EXPERIENCE RULE에 따라 적극적으로 생성한다
- 맛·향·분위기·감정처럼 카테고리에 맞는 주관적 경험과 감상은 방문 정보에 구체적인 묘사가 없어도 카테고리와 입력 정보에서 자연스럽게 추론 가능한 범위에서 적극적으로 새로 생성할 수 있다. 구체적인 방법은 CATEGORY EXPERIENCE RULE을 따른다.
- 단, 방문 정보에 사용자가 이미 구체적으로 적어둔 느낌 묘사가 있다면 그 내용이 항상 우선하고, 새로 생성하는 내용이 그것과 모순되지 않게 한다.
- 실제로 방문(이용)한 것처럼 1인칭으로 표현하는 것 자체는 막지 않는다 — 방문 자체는 이미 사실이므로, A와 달리 그 안에서 느낀 세부 감상은 자유롭게 서술한다.

이 규칙은 응답의 body와 hashtags 모두에 동일하게 적용된다. 해시태그도 A(객관적 정보)는 STORE_INFO·방문 정보에 실제로 근거가 있는 것만 만들고, 방문 정보에서 자연스럽게 파생되는 키워드는 KEYWORD RULE에 따라 만든다.`
}
