export function buildInstagramKeywordGuidanceRule(): string {
  return `본문과 해시태그를 만들기 전에 아래 4가지 종류의 검색 키워드를 머릿속으로 정리한 뒤, 이를 본문 도입부와 해시태그에 자연스럽게 녹인다. 키워드 목록 자체를 결과에 나열하지 않는다.
- Primary Keyword: 지역/동네 + 업종(카테고리)의 조합(예: "광안리 카페"). STORE_INFO나 방문 정보에 지역·카테고리가 있을 때만 만든다.
- Secondary Keyword: 지역/동네 + 대표 메뉴 종류(예: "광안리 빙수")처럼 조금 더 구체적인 조합.
- Store Keyword: 매장명, 매장명 + 업종(예: "온설재", "온설재 카페").
- Menu Keyword: 실제로 방문해서 먹은 메뉴명(예: "복숭아빙수").
같은 키워드를 문장마다 반복 삽입하지 말고, 본문 도입부에는 가능하면 "지역명 + 업종/특징" 조합을 자연스럽게 배치하며, 나머지 키워드는 문맥에 자연스럽게 한 번씩만 녹인다. "OO 카페 추천", "OO 카페 맛집", "OO 카페 인기"처럼 같은 어근을 살짝만 바꿔 반복하는 방식은 사용하지 않는다.`
}
