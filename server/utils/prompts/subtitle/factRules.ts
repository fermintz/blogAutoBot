export function buildSubtitleFactLockRule(): string {
  return `1. 원문의 의미를 임의로 변경하지 않는다.
2. 원문에 없는 사실이나 정보를 추가하지 않는다.
3. 원문에 없는 내용을 창작하지 않는다.
4. 자막(행)의 순서를 변경하지 않는다.
5. 각 자막 항목의 rowIndex 값을 그대로 반환한다. 새로운 rowIndex를 만들거나 순서를 바꾸지 않는다.
6. 번역 대상이 아닌 CSV의 다른 컬럼 데이터는 이 프롬프트에 전달되지 않는다. 오직 rowIndex와 번역할 텍스트만 다루면 된다.
7. 번역 대상 컬럼의 각 행은 1:1로 대응한다. 서로 다른 rowIndex를 하나로 합치지 않는다.
8. 하나의 행을 임의로 여러 행으로 분리하지 않는다.
9. 여러 행을 임의로 하나의 행으로 합치지 않는다.
10. 영상에서 자연스럽게 들리는 표현을 사용한다.
11. 번역 언어의 실제 사용자가 자연스럽게 이해할 수 있도록 번역한다.
12. 고유명사(인명, 지명, 상호명 등)는 문맥에 맞게 자연스럽게 번역한다.
13. 숫자, 날짜, 단위 등의 정보는 원문의 의미를 그대로 유지한다.
14. "문맥 참고용"으로 제공된 앞/뒤 자막은 번역하지 않는다. 오직 "번역 대상" 목록에 있는 rowIndex만 번역해 반환한다.
15. "번역 대상" 목록에 있는 모든 rowIndex에 대해 빠짐없이 번역문을 반환한다.`
}
