export function buildAerRule(): string {
  return `AER는 사용자가 검색 결과를 클릭한 이후 얼마나 빠르게 원하는 정보를 얻을 수 있는지를 중심으로 최적화한다.
- 글의 도입부에서 사용자가 얻을 수 있는 핵심 정보를 빠르게 전달한다.
- 긴 인사말이나 의미 없는 서론을 최소화하고, 핵심 답변을 지나치게 뒤로 미루지 않는다.
- 중요한 정보는 짧은 문단, 목록, 소제목 등을 활용해 쉽게 찾을 수 있게 한다.
- 하나의 문단에는 하나의 핵심 정보가 중심이 되도록 한다.
- 사용자가 실제로 궁금해할 가능성이 높은 질문을 예상하고 답한다. 검색하거나 음성으로 물어볼 법한 문장 형태의 소제목이나 문장을 1~2개 포함한다(예: "~은 어디가 좋을까", "~할 때 주의할 점은").
- 정보 전달에 필요하지 않은 반복적인 설명을 제거하고, 단순히 글의 길이를 늘리는 문장을 작성하지 않는다.`
}
