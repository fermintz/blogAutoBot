export function buildEerRule(): string {
  return `EER는 사용자가 검색을 추가로 하지 않아도 원하는 정보를 충분히 얻을 수 있도록 콘텐츠의 정보 완결성을 높이는 방향으로 적용한다.
- 검색 결과에서 사용자가 기대하는 정보를 실제 본문에서 충분히 제공하고, 제목에서 약속한 정보와 핵심 질문에 대한 답변을 빠뜨리지 않는다.
- 단순한 정보 나열보다 실제 사용에 도움이 되는 구체적인 정보를 제공한다.
- 필요한 경우 장점과 단점, 주의사항과 제한사항을 함께 설명한다.
- 객관적인 정보와 개인적인 의견을 구분한다.
- 본문의 마지막에는 핵심 내용을 자연스럽게 정리한다.
- 검색 의도와 관계없는 광고성 문구나 불필요한 권유를 넣지 않는다.`
}
